# ==============================================================================
# Combined 2x2 Figure: Quartic Potential + Lotka-Volterra
# ==============================================================================
#
# This script creates a combined 2x2 figure with:
#   Row 1: Quartic potential 2D results (state error, energy error)
#   Row 2: Lotka-Volterra results (state error, constraint error)
#
# Usage:
#   include("combined_comparison.jl")
#   main()
#
# Prerequisites:
#   Run quartic_potential_2d.jl and lotka_volterra.jl with save_data=true first.

using ProjectedNDEs:
    ProjectedNDEs,
    QuarticPotential2D,
    LotkaVolterra,
    constraints,
    get_mean_relative_state_error,
    get_mean_relative_constraint_error
using JLD2
using CairoMakie
using Colors

# ==============================================================================
# Configuration
# ==============================================================================

const PROJECT_ROOT = dirname(@__DIR__)

# Data files (generated by quartic_potential_2d.jl and lotka_volterra.jl with save_data=true)
const QUARTIC_DATA = joinpath(@__DIR__, "data", "quartic_potential_2d.jld2")
const LV_DATA = joinpath(@__DIR__, "data", "lotka_volterra.jld2")

# ==============================================================================
# Plotting Configuration
# ==============================================================================

include(joinpath(@__DIR__, "plot_colors.jl"))

# ==============================================================================
# Data Loading
# ==============================================================================

function load_predictions(data::Dict, prefix::String = "predictions_")
    predictions = Dict{Symbol,Any}()
    for (key, value) in data
        key_str = string(key)
        if startswith(key_str, prefix)
            model_name = Symbol(replace(key_str, prefix => ""))
            predictions[model_name] = value
        end
    end
    return predictions
end

# ==============================================================================
# Figure Creation
# ==============================================================================

function create_combined_figure(; save_figure::Bool = true)
    # Load data
    println("Loading quartic potential data from $QUARTIC_DATA...")
    quartic_data = load(QUARTIC_DATA)
    quartic_times = quartic_data["times"]
    quartic_target = quartic_data["target_trajectories"]
    quartic_predictions = load_predictions(quartic_data)

    println("Loading Lotka-Volterra data from $LV_DATA...")
    lv_data = load(LV_DATA)
    lv_times = lv_data["times"]
    lv_target = lv_data["target_trajectories"]
    lv_predictions = load_predictions(lv_data)

    # Create systems for constraint calculations
    quartic_system = QuarticPotential2D{Float32}()
    lv_system = LotkaVolterra{Float32}()

    # Figure dimensions: 245pt width (same as individual figures), ~310pt height for 2 rows
    fig = Figure(size = (245, 270), fontsize = 7, figure_padding = (1, 3, 2, 0))

    # Define model order for both systems
    # Quartic: includes SNDE variants
    quartic_model_order = [:nde, #=:snde_0p1,=# :snde_1p0, :snde_10p0, :pnde]
    quartic_models = filter(k -> k in keys(quartic_predictions), quartic_model_order)

    # Lotka-Volterra: only NDE and PNDE
    lv_model_order = [:nde, :pnde]
    lv_models = filter(k -> k in keys(lv_predictions), lv_model_order)

    # Row labels (vertical, bold)
    Label(
        fig[1, 0],
        "2-D Quartic Potential",
        rotation = π / 2,
        font = :bold,
        fontsize = 8,
        tellheight = false,
    )
    Label(
        fig[2, 0],
        "Lotka-Volterra",
        rotation = π / 2,
        font = :bold,
        fontsize = 8,
        tellheight = false,
    )

    # Row 1: Quartic potential
    # (a) Relative state error
    ax1 = Axis(
        fig[1, 1],
        ylabel = "Relative State Error",
        aspect = 1,
        title = "(a)",
        titlefont = :bold,
        titlegap = 2,
        xticklabelsvisible = false,
        ylabelpadding = 2,
        yticklabelpad = 2,
    )

    for model in quartic_models
        pred = quartic_predictions[model]
        rel_err = get_mean_relative_state_error(pred, quartic_target)
        lines!(ax1, quartic_times, rel_err, color = get_color(model), linewidth = 1)
    end

    # (b) Energy error (log scale)
    ax2 = Axis(
        fig[1, 2],
        ylabel = "Constraint Error",
        yscale = log10,
        aspect = 1,
        title = "(b)",
        titlefont = :bold,
        titlegap = 2,
        xticklabelsvisible = false,
        ylabelpadding = 2,
        yticklabelpad = 2,
    )

    for model in quartic_models
        pred = quartic_predictions[model]
        energy_err =
            get_mean_relative_constraint_error(quartic_system, pred, quartic_target)
        lines!(ax2, quartic_times, energy_err, color = get_color(model), linewidth = 1)
    end

    # Row 2: Lotka-Volterra
    # (c) Relative state error
    ax3 = Axis(
        fig[2, 1],
        xlabel = "Time [s]",
        ylabel = "Relative State Error",
        aspect = 1,
        title = "(c)",
        titlefont = :bold,
        titlegap = 2,
        xlabelpadding = 1,
        xticklabelpad = 2,
        ylabelpadding = 2,
        yticklabelpad = 2,
    )

    for model in lv_models
        pred = lv_predictions[model]
        rel_err = get_mean_relative_state_error(pred, lv_target)
        lines!(ax3, lv_times, rel_err, color = get_color(model), linewidth = 1)
    end

    # (d) Constraint error (log scale)
    ax4 = Axis(
        fig[2, 2],
        xlabel = "Time [s]",
        ylabel = "Constraint Error",
        yscale = log10,
        aspect = 1,
        title = "(d)",
        titlefont = :bold,
        titlegap = 2,
        xlabelpadding = 1,
        xticklabelpad = 2,
        ylabelpadding = 2,
        yticklabelpad = 2,
    )

    for model in lv_models
        pred = lv_predictions[model]
        # Check for negative values (physical constraint violation)
        if any(pred .< 0)
            # Find last valid timestep (before any trajectory goes negative)
            last_valid = 1
            for t_idx = 1:size(pred, 2)
                if all(pred[:, t_idx, :] .> 0)
                    last_valid = t_idx
                else
                    break
                end
            end
            if last_valid > 1
                constraint_err = get_mean_relative_constraint_error(
                    lv_system,
                    pred[:, 1:last_valid, :],
                    lv_target[:, 1:last_valid, :],
                )
                lines!(
                    ax4,
                    lv_times[1:last_valid],
                    constraint_err,
                    color = get_color(model),
                    linewidth = 1,
                )
            end
        else
            constraint_err = get_mean_relative_constraint_error(lv_system, pred, lv_target)
            lines!(ax4, lv_times, constraint_err, color = get_color(model), linewidth = 1)
        end
    end

    # Combined legend with all models from both systems
    all_models = unique([quartic_models..., lv_models...])
    # Maintain order: NDE, SNDEs, PNDE
    model_order = [:nde, #=:snde_0p1,=# :snde_1p0, :snde_10p0, :pnde]
    ordered_all_models = filter(m -> m in all_models, model_order)

    linewidth = 2
    elements = [LineElement(; color = get_color(m), linewidth) for m in ordered_all_models]
    labels = [get_label(m) for m in ordered_all_models]

    Legend(
        fig[3, 0:2],
        elements,
        labels,
        orientation = :horizontal,
        tellwidth = false,
        tellheight = true,
        nbanks = 2,
        rowgap = 2,
        colgap = 8,
        patchsize = (15, 8),
        padding = (4, 4, 4, 4),
    )

    # Make the row label column narrow (Auto for axes, Fixed for labels)
    colsize!(fig.layout, 0, Auto())
    colgap!(fig.layout, 1, 2)
    colgap!(fig.layout, 2, 6)
    rowgap!(fig.layout, 3)

    if save_figure
        output_path = joinpath(@__DIR__, "figures", "combined_qp_lv.pdf")
        CairoMakie.save(output_path, fig)
        println("Saved figure to $output_path")
    end

    return fig
end

# ==============================================================================
# Main Entry Point
# ==============================================================================

function main(; save_figure::Bool = true)
    println("="^60)
    println("Combined Quartic Potential + Lotka-Volterra Figure")
    println("="^60)

    # Check that data files exist
    if !isfile(QUARTIC_DATA)
        error(
            "Quartic potential data not found at $QUARTIC_DATA\n" *
            "Run quartic_potential_2d.jl with save_data=true first.",
        )
    end
    if !isfile(LV_DATA)
        error(
            "Lotka-Volterra data not found at $LV_DATA\n" *
            "Run lotka_volterra.jl with save_data=true first.",
        )
    end

    fig = create_combined_figure(; save_figure)
    display(fig)

    return fig
end

# Run if executed as script
if abspath(PROGRAM_FILE) == @__FILE__
    main()
end
